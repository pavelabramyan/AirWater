def get_region_name(code: str) -> str:
    """Получить название региона по коду"""
    return REGIONS_RF.get(code, f"Регион {code}")


def get_all_regions() -> Dict[str, str]:
    """Получить все регионы"""
    return REGIONS_RF.copy()


def get_popular_regions() -> List[tuple]:
    """Получить популярные регионы (код, название)"""
    return [(code, REGIONS_RF[code]) for code in POPULAR_REGIONS if code in REGIONS_RF]


def get_region_bbox(code: str) -> Dict[str, float]:
    """Получить bbox региона (если доступно)"""
    return REGION_BBOX.get(code)


def search_regions(query: str) -> List[tuple]:
    """Поиск регионов по названию"""
    query_lower = query.lower()
    results = []
    
    for code, name in REGIONS_RF.items():
        if query_lower in name.lower() or query in code:
            results.append((code, name))
    
    return results















